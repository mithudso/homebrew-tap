#!/usr/bin/env python3
"""Generate a shallow, deterministic path index; never read or embed file bodies."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile


OUTPUTS = ("docs/high_signal_file_index.json", "docs/codebase-overview.md", "llms.txt")


def markdown_path(path: str) -> str:
    """Keep Git filenames inside one code cell, including unusual characters."""
    text = json.dumps(path, ensure_ascii=True).replace("|", r"\|")
    width = max((len(run) for run in re.findall(r"`+", text)), default=0) + 1
    fence = "`" * width
    return f"{fence}{text}{fence}"


def render(root: Path) -> dict[str, str]:
    """Describe tracked and nonignored new files in the Git worktree."""
    result = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        cwd=root, check=True, capture_output=True, text=True,
    )
    paths = sorted(set(result.stdout.rstrip("\0").split("\0")) | set(OUTPUTS))
    entries = []
    for path in paths:
        if not path or (path not in OUTPUTS and not (root / path).is_file()):
            continue
        if path.startswith("Formula/"):
            purpose, layer = "Homebrew installation and smoke-test definition", "config"
        elif path.startswith("scripts/"):
            purpose, layer = "Offline repository maintenance command", "tooling"
        elif path.startswith("tests/"):
            purpose, layer = "Behavioral tests for local maintenance tooling", "test"
        elif path.startswith((".github/", ".vscode/")) or path.startswith("."):
            purpose, layer = "Repository workflow or editor configuration", "config"
        else:
            purpose, layer = "Contributor reference and maintenance documentation", "docs"
        entries.append({"path": path, "purpose": purpose, "layer": layer})
    index = json.dumps(entries, indent=2) + "\n"
    table = "# Codebase overview\n\nGenerated by `python3 scripts/generate-doc-indexes.py`. This is a shallow\npath census, not a claim that every document is an independent code audit.\n\n| Path | Purpose |\n| --- | --- |\n"
    table += "".join(f"| {markdown_path(e['path'])} | {e['purpose']} |\n" for e in entries)
    llms = "# Personal Homebrew tap\n\n> Three pinned application formulae; no application runtime or credentials.\n\n- [Wiki](docs/wiki/index.md)\n- [Architecture](docs/ARCHITECTURE.md)\n- [Development](docs/DEVELOPMENT.md)\n- [Testing](docs/TESTING.md)\n- [Security](docs/SECURITY.md)\n- [Complete file map](docs/codebase-overview.md)\n- [Machine path index](docs/high_signal_file_index.json)\n\nThis static navigation contains no embeddings or private file bodies.\n"
    return dict(zip(OUTPUTS, (index, table, llms)))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on stale generated files")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    # Validate every destination before writing any file. Atomic replacement
    # below replaces a destination symlink rather than following it.
    for name in OUTPUTS:
        path = root / name
        if path.is_symlink() or not path.parent.resolve().is_relative_to(root):
            parser.exit(1, f"unsafe generated output: {name}\n")
    stale = []
    for name, content in render(root).items():
        path = root / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = None
            try:
                with tempfile.NamedTemporaryFile(
                    mode="w", encoding="utf-8", dir=path.parent,
                    prefix=".doc-index-", delete=False,
                ) as stream:
                    temporary = Path(stream.name)
                    stream.write(content)
                os.replace(temporary, path)
            finally:
                if temporary is not None:
                    temporary.unlink(missing_ok=True)
    if stale:
        parser.exit(1, "stale generated indexes: " + ", ".join(stale) + "\n")
    print("static indexes OK" if args.check else "static indexes generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
